import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';
const exec=promisify(execFile);
const selected=new Map();
for(const target of ['x86_64-unknown-linux-gnu','aarch64-apple-darwin','x86_64-pc-windows-msvc']){
 const {stdout}=await exec('cargo',['metadata','--locked','--format-version','1','--filter-platform',target],{maxBuffer:16*1024*1024});
 const meta=JSON.parse(stdout), nodes=new Map(meta.resolve.nodes.map(n=>[n.id,n]));
 const pending=[meta.resolve.root], seen=new Set();
 while(pending.length){const id=pending.pop();if(seen.has(id))continue;seen.add(id);for(const d of nodes.get(id)?.deps??[])pending.push(d.pkg);}
 for(const p of meta.packages)if(p.source&&seen.has(p.id))selected.set(p.id,p);
}
const packages=[...selected.values()].sort((a,b)=>(a.name+' '+a.version).localeCompare(b.name+' '+b.version,'en'));
const lock=(await readFile(new URL('../Cargo.lock',import.meta.url),'utf8')).replace(/\r\n/g,'\n');
let text='Herdr Auto Titles — Rust dependency notices\n\nGenerated by node scripts/notices.mjs from the locked dependency graphs for the three native release targets,\nincluding their platform-specific and build dependencies. Root license/notice files are preserved\nbelow. The app/mod/font/icon notices are in LICENSE, NOTICE and licenses/.\n\nCargo.lock SHA256: '+createHash('sha256').update(lock).digest('hex')+'\n';
for(const p of packages){
 const root=dirname(p.manifest_path);
 const files=(await readdir(root,{withFileTypes:true})).filter(e=>e.isFile()&&/^(?:licen[cs]e|copying|copyright|notice)(?:[._-].*)?$/i.test(e.name)).map(e=>e.name).sort();
 if(!files.length) throw Error('No upstream license text found for '+p.name);
 text+=`\n${'='.repeat(72)}\n${p.name} ${p.version}\nLicense expression: ${p.license}\nSource: ${p.repository || p.source}\n`;
 for(const file of files)text+=`\n--- ${file} ---\n`+(await readFile(join(root,file),'utf8')).replace(/\r\n/g,'\n').trimEnd()+'\n';
}
const output=new URL('../THIRD-PARTY-NOTICES',import.meta.url);
if(process.argv.includes('--check')){if((await readFile(output,'utf8')).replace(/\r\n/g,'\n')!==text)throw Error('Dependency notices are stale; run node scripts/notices.mjs');}
else await writeFile(output,text);
